logger = logging.getLogger(__name__)

STYLE_FILE_NAME = "style.css"
PROJECT_URL = "https://github.com/lncrawl/lightnovel-crawler"


def _xml(value) -> str:
    return escape(str(value or ""), {'"': "&quot;", "'": "&apos;"})


def _xhtml(title: str, body: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <title>{_xml(title)}</title>
  <link rel="stylesheet" type="text/css" href="style.css"/>
</head>
<body>
{body}
</body>
</html>
"""


def _chapter_xhtml(chapter, content: str) -> str:
    body = f"""
<div id="chapter">
  <h4 style="opacity: 0.75" aria-hidden="true">#{chapter.serial}</h4>
  <h1>{_xml(chapter.title)}</h1>
  {content or "<p><em>No content available</em></p>"}
</div>
"""
    return _xhtml(chapter.title, body)


def _intro_xhtml(novel) -> str:
    body = f"""
<div id="intro">
  <h1>{_xml(novel.title)}</h1>
  <h3>{_xml(novel.authors)}</h3>
  <div class="synopsis">
    {novel.synopsis or ""}
  </div>
  <div class="footer">
    <b>Source:</b> <a href="{_xml(novel.url)}">{_xml(novel.url)}</a>
    <br/><br/>
    <i>Generated by <b>
    <a href="{PROJECT_URL}">Lightnovel Crawler</a></b></i>
    <br/>
    Made by Telegram bot:
    <a href="https://t.me/lightnovel_crawer_bot">BOT: Novel Downloader</a>
    <br/>
    Telegram group:
    <a href="https://t.me/novelsFinder">Webnovels and Wuxia Novels</a>
  </div>
</div>
"""
    return _xhtml("Introduction", body)


def _volume_xhtml(volume) -> str:
    return _xhtml(
        volume.title,
        f"<div id=\"volume\"><h1>{_xml(volume.title)}</h1></div>",
    )


def _cover_xhtml() -> str:
    return _xhtml(
        "Cover",
        '<div id="cover"><img src="images/cover.jpg" alt="cover"/></div>',
    )


def _container_xml() -> str:
    return """<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf"
              media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
"""


def _nav_xhtml(novel, volume_entries) -> str:
    entries = [
        '<li><a href="intro.xhtml">Introduction</a></li>'
    ]

    for volume, chapters in volume_entries:
        if not chapters:
            continue

        chapter_links = "".join(
            f'<li><a href="{href}">{_xml(title)}</a></li>'
            for href, title in chapters
        )

        entries.append(
            f"<li><span>{_xml(volume.title)}</span>"
            f"<ol>{chapter_links}</ol></li>"
        )

    return f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml"
      xmlns:epub="http://www.idpf.org/2007/ops">
<head>
  <title>{_xml(novel.title)}</title>
  <link rel="stylesheet" type="text/css" href="style.css"/>
</head>
<body>
  <nav epub:type="toc" id="toc">
    <h1>Table of Contents</h1>
    <ol>
      {''.join(entries)}
    </ol>
  </nav>
</body>
</html>
"""

def _toc_ncx(novel, volume_entries) -> str:
    nav_points = []
    play_order = 1

    nav_points.append(
        f"""
        <navPoint id="intro" playOrder="{play_order}">
          <navLabel><text>Introduction</text></navLabel>
          <content src="intro.xhtml"/>
        </navPoint>
        """
    )
    play_order += 1

    for volume, chapters in volume_entries:
        if not chapters:
            continue

        volume_order = play_order
        play_order += 1
        chapter_points = []

        for href, title in chapters:
            chapter_points.append(
                f"""
                <navPoint id="nav-{play_order}" playOrder="{play_order}">
                  <navLabel><text>{_xml(title)}</text></navLabel>
                  <content src="{href}"/>
                </navPoint>
                """
            )
            play_order += 1

        nav_points.append(
            f"""
            <navPoint id="volume-{volume.serial}" playOrder="{volume_order}">
              <navLabel><text>{_xml(volume.title)}</text></navLabel>
              <content src="volume_{volume.serial:03}.xhtml"/>
              {''.join(chapter_points)}
            </navPoint>
            """
        )

    return f"""<?xml version="1.0" encoding="UTF-8"?>
<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/"
     version="2005-1">
  <head>
    <meta name="dtb:uid" content="{_xml(novel.id)}"/>
  </head>
  <docTitle><text>{_xml(novel.title)}</text></docTitle>
  <navMap>
    {''.join(nav_points)}
  </navMap>
</ncx>
"""

def _content_opf(novel, language, has_cover, image_entries, volume_entries) -> str:
    manifest = [
        '<item id="style" href="style.css" media-type="text/css"/>',
        '<item id="intro" href="intro.xhtml" media-type="application/xhtml+xml"/>',
        '<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>',
        '<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>',
    ]

    spine = [
    '<itemref idref="intro"/>',
    '<itemref idref="nav"/>',
]

    if has_cover:
        manifest.extend(
            [
                '<item id="cover-image" href="images/cover.jpg" media-type="image/jpeg" properties="cover-image"/>',
                '<item id="cover-page" href="cover.xhtml" media-type="application/xhtml+xml"/>',
            ]
        )
        spine.insert(0, '<itemref idref="cover-page"/>')

    # Important: volume page, then that volume's chapters.
    for volume, chapters in volume_entries:
        if not chapters:
            continue

        volume_id = f"volume_{volume.serial}"
        manifest.append(
            f'<item id="{volume_id}" href="volume_{volume.serial:03}.xhtml" '
            'media-type="application/xhtml+xml"/>'
        )
        spine.append(f'<itemref idref="{volume_id}"/>')

        for href, _title in chapters:
            serial = int(href.removeprefix("chapter_").removesuffix(".xhtml"))
            chapter_id = f"chapter_{serial}"

            manifest.append(
                f'<item id="{chapter_id}" href="{href}" '
                'media-type="application/xhtml+xml"/>'
            )
            spine.append(f'<itemref idref="{chapter_id}"/>')

    for image_id in image_entries:
        manifest.append(
            f'<item id="image_{image_id}" href="images/{image_id}.jpg" '
            'media-type="image/jpeg"/>'
        )

    subjects = "".join(
        f"<dc:subject>{_xml(tag)}</dc:subject>"
        for tag in (novel.tags or [])
    )

    direction = (
        ' page-progression-direction="rtl"'
        if novel.rtl
        else ""
    )

    return f"""<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf"
         unique-identifier="book-id"
         version="3.0">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="book-id">{_xml(novel.id)}</dc:identifier>
    <dc:title>{_xml(novel.title)}</dc:title>
    <dc:language>{_xml(language or novel.language or "en")}</dc:language>
    <dc:creator>{_xml(novel.authors)}</dc:creator>
    <dc:description>{_xml(novel.synopsis)}</dc:description>
    {subjects}
  </metadata>
  <manifest>
    {''.join(manifest)}
  </manifest>
  <spine toc="ncx"{direction}>
    {''.join(spine)}
  </spine>
</package>
"""


def make_epub(working_dir: Path, artifact: Artifact, signal=Event(), **kwargs) -> None:
    """
    Create an EPUB directly on disk.

    Only one chapter body or image is loaded at a time. The small chapter/title
    manifest remains in RAM, but the whole novel and all images do not.
    """
    out_file = ctx.files.resolve(artifact.output_file)
    tmp_file = working_dir / out_file.name

    language = LanguageCode(artifact.language) if artifact.language else None
    novel = ctx.novels.get(artifact.novel_id, language)

    if artifact.volume is not None:
        volumes = [
            ctx.volumes.find_translated(
                artifact.novel_id,
                artifact.volume,
                language,
            )
        ]
    else:
        volumes = ctx.volumes.list(artifact.novel_id, language)

    # Small metadata only: serial/title/file names, never chapter body text.
    chapter_entries = []
    volume_entries = []

    for volume in volumes:
        chapters_for_volume = []

        for chapter in ctx.chapters.list(volume_id=volume.id, language=language):
            if not chapter.is_available:
                continue

            href = f"chapter_{chapter.serial:05}.xhtml"
            chapter_entries.append((chapter.serial, chapter.title))
            chapters_for_volume.append((href, chapter.title))

        volume_entries.append((volume, chapters_for_volume))

    # Keep only image IDs in RAM; image bytes stay on disk until copied.
    image_entries = [
        image.id
        for image in ctx.images.list(novel_id=artifact.novel_id)
        if image.is_available
    ]

    has_cover = novel.cover_available
    cover_file = ctx.files.resolve(novel.cover_file) if has_cover else None

    try:
        with ZipFile(
            tmp_file,
            mode="w",
            compression=ZIP_DEFLATED,
            compresslevel=6,
            allowZip64=True,
        ) as archive:
            # EPUB specification requires this first and uncompressed.
            archive.writestr(
                "mimetype",
                "application/epub+zip",
                compress_type=ZIP_STORED,
            )

            archive.writestr("META-INF/container.xml", _container_xml())
            archive.writestr(f"OEBPS/{STYLE_FILE_NAME}", epub_style_css())

            if signal.is_set():
                raise AbortedException()

            if has_cover and cover_file and cover_file.is_file():
                archive.write(cover_file, "OEBPS/images/cover.jpg")
                archive.writestr("OEBPS/cover.xhtml", _cover_xhtml())

            archive.writestr("OEBPS/intro.xhtml", _intro_xhtml(novel))

            # Chapters are read, written, then released one at a time.
            for volume, _chapters in volume_entries:
                if signal.is_set():
                    raise AbortedException()

                archive.writestr(
                    f"OEBPS/volume_{volume.serial:03}.xhtml",
                    _volume_xhtml(volume),
                )

                for chapter in ctx.chapters.list(
                    volume_id=volume.id,
                    language=language,
                ):
                    if signal.is_set():
                        raise AbortedException()

                    if not chapter.is_available:
                        continue

                    if language:
                        translated = ctx.chapters.get_chapter_translation(
                            chapter,
                            language,
                        )
                        content = (
                            ctx.files.load_text(translated.content_file)
                            if translated and translated.is_available
                            else ""
                        )
                    else:
                        content = ctx.files.load_text(chapter.content_file)

                    archive.writestr(
                        f"OEBPS/chapter_{chapter.serial:05}.xhtml",
                        _chapter_xhtml(chapter, content),
                    )

            # Images are copied from disk directly into the EPUB ZIP.
            for image in ctx.images.list(novel_id=artifact.novel_id):
                if signal.is_set():
                    raise AbortedException()

                if not image.is_available:
                    continue

                image_file = ctx.files.resolve(image.image_file)
                archive.write(image_file, f"OEBPS/images/{image.id}.jpg")

            archive.writestr(
                "OEBPS/nav.xhtml",
                _nav_xhtml(novel, volume_entries),
            )

            archive.writestr(
                "OEBPS/toc.ncx",
                _toc_ncx(novel, volume_entries),
            )

            archive.writestr(
                "OEBPS/content.opf",
                _content_opf(
                    novel,
                    artifact.language or novel.language,
                    has_cover,
                    image_entries,
                    volume_entries,
                ),
            )

        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.unlink(True)
        shutil.move(str(tmp_file), str(out_file))
        logger.info("Created streaming EPUB: %s", out_file)

    finally:
        tmp_file.unlink(missing_ok=True)